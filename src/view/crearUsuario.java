    public class ValidacionRegistro {

        // Componentes del formulario (asumiendo que son campos de texto JTextField)
        private JTextField txtNombre;
        private JTextField txtApellido;
        private JTextField txtDocumento;
        private JTextField txtDireccion;
        private JPasswordField txtContraseña;
        private JDateChooser dateChooserFechaNacimiento;

        // Constructor que recibe los componentes
        public ValidacionRegistro(JTextField nombre, JTextField apellido, JTextField documento,
                JTextField direccion, JPasswordField contraseña, JDateChooser fechaNacimiento) {
            this.txtNombre = nombre;
            this.txtApellido = apellido;
            this.txtDocumento = documento;
            this.txtDireccion = direccion;
            this.txtContraseña = contraseña;
            this.dateChooserFechaNacimiento = fechaNacimiento;
        }

        /**
         * Valida todos los campos del formulario y la edad del usuario
         *
         * @return true si todos los campos son válidos y el usuario es mayor de
         * 18 años, false en caso contrario
         */
        public boolean validarRegistro() {
            // Validar campos vacíos
            if (txtNombre.getText().trim().isEmpty()
                    || txtApellido.getText().trim().isEmpty()
                    || txtDocumento.getText().trim().isEmpty()
                    || txtDireccion.getText().trim().isEmpty()
                    || txtContraseña.getPassword().length == 0) {

                JOptionPane.showMessageDialog(null, "Todos los campos son obligatorios", "Error", JOptionPane.ERROR_MESSAGE);
                return false;
            }

            // Validar fecha de nacimiento
            if (dateChooserFechaNacimiento.getDate() == null) {
                JOptionPane.showMessageDialog(null, "Debe seleccionar una fecha de nacimiento", "Error", JOptionPane.ERROR_MESSAGE);
                return false;
            }

            // Calcular edad
            Date fechaNac = dateChooserFechaNacimiento.getDate();
            int edad = calcularEdad(fechaNac);

            if (edad < 18) {
                JOptionPane.showMessageDialog(null, "Debe ser mayor de 18 años para registrarse", "Error", JOptionPane.ERROR_MESSAGE);
                return false;
            }

            // Si todo está correcto
            return true;
        }

        /**
         * Calcula la edad basada en la fecha de nacimiento
         *
         * @param fechaNacimiento Fecha de nacimiento del usuario
         * @return Edad calculada
         */
        private int calcularEdad(Date fechaNacimiento) {
            Calendar fechaNac = Calendar.getInstance();
            fechaNac.setTime(fechaNacimiento);

            Calendar fechaActual = Calendar.getInstance();

            int edad = fechaActual.get(Calendar.YEAR) - fechaNac.get(Calendar.YEAR);

            // Ajustar si aún no ha pasado el cumpleaños este año
            if (fechaActual.get(Calendar.MONTH) < fechaNac.get(Calendar.MONTH)) {
                edad--;
            } else if (fechaActual.get(Calendar.MONTH) == fechaNac.get(Calendar.MONTH)
                    && fechaActual.get(Calendar.DAY_OF_MONTH) < fechaNac.get(Calendar.DAY_OF_MONTH)) {
                edad--;
            }

            return edad;
        }
    }

