    private void cargarDescripcionEImagen() {
        String rolSeleccionado = (String) rolesBox.getSelectedItem();

        if (rolSeleccionado != null) {
            // Cargar descripción
            String descripcion = descripcionesRoles.get(rolSeleccionado);
            descripcionArea.setText(descripcion != null ? descripcion : "Descripción no disponible");

            // Cargar imagen
            String rutaImagen = imagenesRoles.get(rolSeleccionado);
            if (rutaImagen != null) {
                try {
                    ImageIcon icon = new ImageIcon(getClass().getResource(rutaImagen));
                    // Escalar la imagen si es necesario
                    Image imagen = icon.getImage().getScaledInstance(
                            imagenRol.getWidth(),
                            imagenRol.getHeight(),
                            Image.SCALE_SMOOTH);
                    imagenRol.setIcon(new ImageIcon(imagen));
                } catch (Exception e) {
                    imagenRol.setIcon(null);
                    imagenRol.setText("Imagen no encontrada");
                }
            } else {
                imagenRol.setIcon(null);
                imagenRol.setText("Imagen no disponible");
            }
        }
    }

